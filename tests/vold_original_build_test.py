#!/usr/bin/env python3
"""Regression checks for the real Repo layout and fail-closed build inputs."""
from __future__ import annotations

import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src/ci"))
import build_original_vold as builder  # noqa: E402


class OriginalVoldBuildTest(unittest.TestCase):
    def setUp(self):
        self.lock, self.manifest = builder.load_contract()

    def release_config(self, source):
        path = source / self.lock["build"]["release_config"]["path"]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("# Updated manually\naosp_target_release=cp2a\n")

    @staticmethod
    def selected_manifest(source, manifest):
        manifests = source / ".repo/manifests"
        manifests.mkdir(parents=True)
        (manifests / builder.MANIFEST_NAME).write_bytes(manifest)
        # Modern Repo manifest_xml.XmlManifest.Link() writes this include
        # wrapper; it does not copy the selected manifest into manifest.xml.
        active = source / ".repo/manifest.xml"
        active.write_text(
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<!-- DO NOT EDIT THIS FILE! It is generated by repo. -->\n'
            '<manifest>\n'
            f'  <include name="{builder.MANIFEST_NAME}" />\n'
            '</manifest>\n'
        )
        return active

    def test_actual_repo_include_wrapper_and_included_bytes(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp)
            self.selected_manifest(source, self.manifest)
            builder.verify_active_manifest(source, self.manifest)
            (source / ".repo/manifests" / builder.MANIFEST_NAME).write_bytes(b"changed")
            with self.assertRaisesRegex(builder.BuildError, "exact official snapshot"):
                builder.verify_active_manifest(source, self.manifest)

    def test_wrapper_cannot_add_overrides_or_select_another_manifest(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp)
            active = self.selected_manifest(source, self.manifest)
            for contents in (
                '<manifest><include name="default.xml" /></manifest>',
                f'<manifest><include name="{builder.MANIFEST_NAME}" groups="extra" /></manifest>',
                f'<manifest><include name="{builder.MANIFEST_NAME}" /><project name="extra" /></manifest>',
                f'<manifest><include name="{builder.MANIFEST_NAME}" /><include name="extra.xml" /></manifest>',
            ):
                with self.subTest(contents=contents):
                    active.write_text(contents)
                    with self.assertRaisesRegex(builder.BuildError, "wrapper"):
                        builder.verify_active_manifest(source, self.manifest)

    def test_local_manifests_rejected_even_with_matching_active_manifest(self):
        for filename in ("local_manifest.xml", "local_manifests/extra.xml"):
            with self.subTest(filename=filename), tempfile.TemporaryDirectory() as tmp:
                source = Path(tmp)
                self.selected_manifest(source, self.manifest)
                override = source / ".repo" / filename
                override.parent.mkdir(parents=True, exist_ok=True)
                override.write_text("<manifest />")
                with self.assertRaisesRegex(builder.BuildError, "local manifest overrides"):
                    builder.verify_active_manifest(source, self.manifest)

    def test_legacy_manifest_link_must_target_the_pinned_checkout_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp) / "source"
            active = self.selected_manifest(source, self.manifest)
            active.unlink()
            active.symlink_to(Path("manifests") / builder.MANIFEST_NAME)
            builder.verify_active_manifest(source, self.manifest)
            outside = Path(tmp) / "outside.xml"
            outside.write_bytes(self.manifest)
            active.unlink()
            active.symlink_to(outside)
            with self.assertRaisesRegex(builder.BuildError, "link does not select"):
                builder.verify_active_manifest(source, self.manifest)

    def test_omitted_manifest_path_checks_real_git_revision_and_local_content(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp)
            project = source / "device/common"
            project.mkdir(parents=True)
            subprocess.run(["git", "init", "--quiet", str(project)], check=True)
            subprocess.run(
                ["git", "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid",
                 "commit", "--quiet", "--allow-empty", "-m", "pinned fixture"],
                cwd=project, check=True,
            )
            revision = subprocess.run(
                ["git", "rev-parse", "HEAD"], cwd=project, check=True,
                capture_output=True, text=True,
            ).stdout.strip()
            manifest = f'<manifest><project name="device/common" revision="{revision}" /></manifest>'.encode()
            self.selected_manifest(source, manifest)
            with patch.object(builder.shutil, "which", return_value="/trusted/repo"):
                builder.verify_checkout(source, manifest, clean=True, selected=["device/common"])
                (project / "unexpected.bp").write_text("unreviewed source")
                with self.assertRaisesRegex(builder.BuildError, "unreviewed local content"):
                    builder.verify_checkout(source, manifest, clean=True, selected=["device/common"])
                (project / "unexpected.bp").unlink()
                bad = manifest.replace(revision.encode(), b"0" * 40)
                (source / ".repo/manifests" / builder.MANIFEST_NAME).write_bytes(bad)
                with self.assertRaisesRegex(builder.BuildError, "source revision changed"):
                    builder.verify_checkout(source, bad, clean=True, selected=["device/common"])

    def test_resume_fetches_partial_directories_but_not_existing_worktrees(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp)
            self.selected_manifest(source, self.manifest)
            (source / "system/vold/.git").mkdir(parents=True)
            (source / "system/update_engine").mkdir(parents=True)
            calls = []
            with (
                patch.object(builder.shutil, "which", return_value="/trusted/repo"),
                patch.object(builder, "verify_checkout") as verify,
                patch.object(builder, "command", side_effect=lambda args, *a, **k: calls.append(args)),
            ):
                builder.sync(source, self.lock, self.manifest, 2,
                             ["system/vold", "system/update_engine"], resume=True)
            self.assertEqual(calls, [["/trusted/repo", "sync", "--no-clone-bundle", "-j2", "system/update_engine"]])
            self.assertEqual(verify.call_args_list[0].kwargs["selected"], ["system/vold"])

    def test_vendor_prerequisite_mode_only_requests_three_pinned_projects(self):
        with (
            patch.object(sys, "argv", ["builder", "sync-vendor-sources", "--source-root", "/fixture", "--jobs", "2"]),
            patch.object(builder, "sync") as sync,
        ):
            self.assertEqual(builder.main(), 0)
        args = sync.call_args.args
        self.assertEqual(args[0], Path("/fixture"))
        self.assertEqual(args[3], 2)
        self.assertEqual(args[4], ["device/sony/pdx235", "device/sony/sm6375-common", "tools/extract-utils"])
        self.assertTrue(set(args[4]).issubset(builder.project_map(self.manifest)))

    def test_unrecorded_vendor_or_unselected_source_is_not_build_input(self):
        for unexpected in ("vendor/sony/pdx235/Android.bp", "system/update_engine/Android.bp"):
            with self.subTest(unexpected=unexpected), tempfile.TemporaryDirectory() as tmp:
                source = Path(tmp)
                (source / "system/vold").mkdir(parents=True)
                bad = source / unexpected
                bad.parent.mkdir(parents=True, exist_ok=True)
                bad.write_text("unrecorded source")
                with self.assertRaisesRegex(builder.BuildError, "unrecorded source"):
                    builder.verify_source_workspace(source, self.manifest, ["system/vold"])

    def test_manifest_exported_links_are_checked_without_scanning_project_contents(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp)
            project = source / "build/make"
            project.mkdir(parents=True)
            (project / "envsetup.sh").write_text("pinned source")
            link = source / "build/envsetup.sh"
            link.symlink_to("make/envsetup.sh")
            builder.verify_source_workspace(source, self.manifest, ["build/make"])
            link.unlink()
            link.write_text("unreviewed replacement")
            with self.assertRaisesRegex(builder.BuildError, "linkfile differs"):
                builder.verify_source_workspace(source, self.manifest, ["build/make"])

    def test_successful_noop_build_cannot_reuse_prior_vold(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp)
            self.selected_manifest(source, self.manifest)
            self.release_config(source)
            artifact = source / self.lock["build"]["artifact"]
            artifact.parent.mkdir(parents=True)
            artifact.write_bytes(b"previous executable")
            artifact.chmod(0o755)
            with (
                patch.object(builder, "verify_checkout"),
                patch.object(builder, "command"),
                self.assertRaisesRegex(builder.BuildError, "did not produce"),
            ):
                builder.compile_original_vold(source, self.lock, self.manifest, 2)
            self.assertFalse(artifact.exists())

    def test_build_uses_own_output_tree_and_rejects_dependency_bypasses(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp)
            self.selected_manifest(source, self.manifest)
            self.release_config(source)
            artifact = source / self.lock["build"]["artifact"]
            artifact.parent.mkdir(parents=True)

            def compile_fixture(_args, _cwd, *, env):
                self.assertEqual(_args[:2], ["bash", "-ec"])
                self.assertIn("check_product lineage_pdx235 cp2a", _args[2])
                self.assertIn("_lunch_meat lineage_pdx235 cp2a userdebug", _args[2])
                self.assertNotIn("lunch lineage_pdx235-userdebug", _args[2])
                self.assertEqual(env["USE_LEFTOVERS"], "0")
                self.assertEqual(env["PYTHONDONTWRITEBYTECODE"], "1")
                self.assertEqual(env["OUT_DIR"], "out")
                self.assertNotIn("OUT_DIR_COMMON_BASE", env)
                self.assertNotIn("ANDROID_PRODUCT_OUT", env)
                self.assertNotIn("ALLOW_MISSING_DEPENDENCIES", env)
                artifact.write_bytes(b"fresh executable")
                artifact.chmod(0o755)

            with (
                patch.object(builder, "verify_checkout"),
                patch.object(builder, "command", side_effect=compile_fixture),
                patch.dict(os.environ, {"OUT_DIR": "/other-build", "OUT_DIR_COMMON_BASE": "/common", "ANDROID_PRODUCT_OUT": "/other-product", "ALLOW_MISSING_DEPENDENCIES": "false"}),
            ):
                self.assertEqual(builder.compile_original_vold(source, self.lock, self.manifest, 2), artifact)
            for flag in ("SOONG_ALLOW_MISSING_DEPENDENCIES", "ALLOW_MISSING_DEPENDENCIES"):
                with (
                    self.subTest(flag=flag),
                    patch.object(builder, "verify_checkout"),
                    patch.object(builder, "command") as compile_command,
                    patch.dict(os.environ, {flag: "true"}),
                    self.assertRaisesRegex(builder.BuildError, "bypass must be disabled"),
                ):
                    builder.compile_original_vold(source, self.lock, self.manifest, 2)
                compile_command.assert_not_called()

    def test_failed_upstream_setup_or_kernel_autobuild_stops_before_vold(self):
        for setup_failure in (True, False):
            with self.subTest(setup_failure=setup_failure), tempfile.TemporaryDirectory() as tmp:
                source = Path(tmp)
                self.selected_manifest(source, self.manifest)
                self.release_config(source)
                make = source / "build/make"
                make.mkdir(parents=True)
                (source / "build/envsetup.sh").symlink_to("make/envsetup.sh")
                artifact = source / self.lock["build"]["artifact"]
                (make / "envsetup.sh").write_text(
                    "function check_product() { return 0; }\n"
                    "function _lunch_meat() { "
                    + ("return 0;" if setup_failure else "build_kernel;")
                    + " }\n"
                    "function m() { mkdir -p out/target/product/pdx235/system/bin; "
                    "echo stale > out/target/product/pdx235/system/bin/vold; "
                    "chmod +x out/target/product/pdx235/system/bin/vold; }\n"
                    + ("return 1\n" if setup_failure else "return 0\n")
                )
                with (
                    patch.object(builder, "verify_checkout"),
                    self.assertRaises(subprocess.CalledProcessError),
                ):
                    builder.compile_original_vold(source, self.lock, self.manifest, 2)
                self.assertFalse(artifact.exists())

    def test_successful_compiler_cannot_add_an_unrecorded_source_tree(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp)
            self.selected_manifest(source, self.manifest)
            self.release_config(source)
            artifact = source / self.lock["build"]["artifact"]

            def changed_source(_args, _cwd, **_kwargs):
                artifact.parent.mkdir(parents=True)
                artifact.write_bytes(b"fresh executable")
                artifact.chmod(0o755)
                extra = source / "vendor/unrecorded/Android.bp"
                extra.parent.mkdir(parents=True)
                extra.write_text("unrecorded build input")

            with (
                patch.object(builder, "verify_checkout") as verify,
                patch.object(builder, "command", side_effect=changed_source),
                self.assertRaisesRegex(builder.BuildError, "unrecorded source"),
            ):
                builder.compile_original_vold(source, self.lock, self.manifest, 2)
            self.assertEqual(verify.call_count, 2)


if __name__ == "__main__":
    unittest.main()
